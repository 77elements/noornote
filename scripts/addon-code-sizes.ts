/**
 * Addon code-size manifest generator — runs as part of `bun run build`
 * (after `vite build`).
 *
 * Reads the production sourcemaps (dist/assets/js/*.js.map) and maps
 * every chunk to the addon whose `runtime.ts` it contains — exactly the
 * chunk the browser fetches when that addon's runtime loads. Writes the
 * real sizes (raw + gzip) to src/generated/addonCodeSizes.ts.
 *
 * Deliberately NOT chunk-name-based: naming addon chunks via
 * manualChunks makes Rolldown reshuffle shared vendor families (the
 * nostr-tools/crypto family migrated wholesale into the one named
 * addon chunk), which corrupts the bundle graph. Source-map scanning
 * needs no build config at all and reports the true load sizes.
 *
 * Chunks that contain no (or more than one) addon runtime are not
 * addon-attributable and are skipped. Consumers:
 * src/shell/loadHud.ts — measured numbers, not estimates.
 */

import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { gzipSync } from 'node:zlib';
import { join } from 'node:path';

const DIST_DIR = 'dist/assets/js';
const OUT_FILE = 'src/generated/addonCodeSizes.ts';

interface AddonSize {
  bytes: number;
  gzipBytes: number;
}

function measure(): Map<string, AddonSize> {
  const sizes = new Map<string, AddonSize>();
  const runtimePattern = /src\/addons\/([^/]+)\/runtime\.ts/;
  for (const file of readdirSync(DIST_DIR)) {
    if (!file.endsWith('.js.map')) continue;
    let sources: string[] = [];
    try {
      sources =
        (
          JSON.parse(readFileSync(join(DIST_DIR, file), 'utf8')) as {
            sources?: string[];
          }
        ).sources ?? [];
    } catch {
      continue;
    }
    const ids = new Set(
      sources
        .map(s => runtimePattern.exec(s)?.[1])
        .filter((id): id is string => !!id)
    );
    // Exactly one addon runtime per chunk — otherwise unattributable.
    if (ids.size !== 1) continue;
    const [id] = ids;
    const jsFile = file.slice(0, -4); // strip .map
    const path = join(DIST_DIR, jsFile);
    const bytes = statSync(path).size;
    const gzipBytes = gzipSync(readFileSync(path)).length;
    sizes.set(id, { bytes, gzipBytes });
  }
  return sizes;
}

function render(id: string, value: number, indent: string): string {
  // Prettier quoteProps "as-needed": quote only non-identifier keys.
  const key = /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(id) ? id : `'${id}'`;
  return `${indent}${key}: ${value},`;
}

function constBlock(
  name: string,
  comment: string,
  sizes: Map<string, AddonSize>,
  pick: (s: AddonSize) => number
): string {
  const entries = [...sizes.entries()].sort(([a], [b]) => a.localeCompare(b));
  const lines = entries.map(([id, s]) => render(id, pick(s), '    '));
  return `/** ${comment} */\nexport const ${name}: Readonly<Record<string, number>> =\n  Object.freeze({\n${lines.join('\n')}\n  });`;
}

function fileContent(sizes: Map<string, AddonSize>): string {
  const header = `/**
 * GENERATED by \`bun scripts/addon-code-sizes.ts\` (part of
 * \`bun run build\`) — DO NOT EDIT. Real code sizes of the per-addon
 * runtime chunks, identified via sourcemap sources (the chunk the
 * browser fetches when that addon's runtime loads), minified.
 * Consumed by src/shell/loadHud.ts — measured numbers, not estimates.
 */

`;
  return `${header}${constBlock(
    'ADDON_RUNTIME_CODE_BYTES',
    'Minified code size in bytes of the chunk loaded at addon runtime init.',
    sizes,
    s => s.bytes
  )}\n\n${constBlock(
    'ADDON_RUNTIME_GZIP_BYTES',
    'Gzipped transfer size in bytes of the chunk loaded at addon runtime init.',
    sizes,
    s => s.gzipBytes
  )}\n`;
}

const sizes = measure();
if (sizes.size === 0) {
  console.error(
    `addon-code-sizes: no addon runtime chunks found in ${DIST_DIR} — did vite build run?`
  );
  process.exit(1);
}

const next = fileContent(sizes);
let current = '';
try {
  current = readFileSync(OUT_FILE, 'utf8');
} catch {
  /* first generation */
}
if (current !== next) {
  writeFileSync(OUT_FILE, next);
  console.log(`addon-code-sizes: ${sizes.size} addons → ${OUT_FILE}`);
} else {
  console.log(`addon-code-sizes: ${sizes.size} addons (unchanged)`);
}
